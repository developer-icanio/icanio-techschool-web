// Builds rows for Amazon Seller Central's "Category Listings Report"
// bulk-upload template for product type SHIRT — reusing the exact
// column shape imported into marketplaceListingTemplateFields (see
// scripts/import-amazon-listing-template.ts) and the per-SKU values
// already sitting in product_channel_listings.raw_attributes (channel
// "amazon"), rather than re-deriving them from productMasterData's
// named columns — that keeps every one of the 272 real Amazon fields in
// play, not just the ~40 promoted to their own column.
//
// Row layout matches the source template exactly: the real download had
// its label row at row 4, machine attribute-path row at row 5, and data
// starting at row 8 (an example row + an info banner filled rows 6-7,
// left blank here). Row 1 there also carried a settings string
// ("labelRow=4&attributeRow=5...") generated by Amazon's own tool for
// that specific download session — reusing a stale one in a fresh file
// felt riskier than omitting it, so row 1 here is blank. This hasn't
// been test-uploaded to Seller Central; the column positions are exactly
// right, but whether Amazon's importer accepts a file assembled this way
// (versus one freshly downloaded from their tool) hasn't been confirmed.

import { db } from "@/db";
import { productMasterData, productChannelListings, marketplaceListingTemplateFields } from "@/db/schema";
import { and, eq, inArray, asc } from "drizzle-orm";

export const AMAZON_SHEET_NAME = "Template";
const CHANNEL = "amazon" as const;
const PRODUCT_TYPE = "SHIRT";

export async function buildAmazonAoa(parentSkus: string[]): Promise<(string | number)[][]> {
  const fields = await db.query.marketplaceListingTemplateFields.findMany({
    where: and(
      eq(marketplaceListingTemplateFields.channel, CHANNEL),
      eq(marketplaceListingTemplateFields.productType, PRODUCT_TYPE)
    ),
    orderBy: asc(marketplaceListingTemplateFields.columnIndex),
  });
  const columnCount = fields.length;
  const blankRow = (): string[] => new Array(columnCount).fill("");
  const labelRow = fields.map((f) => f.label);
  const attributePathRow = fields.map((f) => f.attributePath);

  const parents = await db.query.productMasterData.findMany({
    where: inArray(productMasterData.sku, parentSkus),
  });
  const children = await db.query.productMasterData.findMany({
    where: inArray(productMasterData.parentSku, parentSkus),
    orderBy: asc(productMasterData.sizeLabel),
  });

  const relevantSkus = [...parents.map((p) => p.sku), ...children.map((c) => c.sku)];
  const listings = await db.query.productChannelListings.findMany({
    where: and(eq(productChannelListings.channel, CHANNEL), inArray(productChannelListings.sku, relevantSkus)),
  });
  const rawAttrsBySku = new Map(listings.map((l) => [l.sku, l.rawAttributes as Record<string, unknown>]));

  function buildRow(sku: string): (string | number)[] {
    const attrs = rawAttrsBySku.get(sku) ?? {};
    return fields.map((f) => {
      const v = attrs[f.attributePath];
      if (v == null) return "";
      return Array.isArray(v) ? v.join(", ") : (v as string | number);
    });
  }

  const dataRows: (string | number)[][] = [];
  for (const parent of parents) {
    dataRows.push(buildRow(parent.sku));
    // A Parent row's own parentSku points at itself (not null — see
    // productMasterData's schema comment), so it self-matches this query
    // and would otherwise get pushed a second time as if it were its own
    // child. c.color excludes it the same way lib/exports/myntra.ts
    // already does: only a real Child row has a color set.
    const activeChildren = children.filter((c) => c.parentSku === parent.sku && c.isActive && c.color);
    for (const child of activeChildren) {
      dataRows.push(buildRow(child.sku));
    }
  }

  return [
    blankRow(), // row1 - settings row in the source file, left blank here (see file header note)
    blankRow(), // row2
    blankRow(), // row3
    labelRow, // row4 - human labels
    attributePathRow, // row5 - machine attribute paths
    blankRow(), // row6 - example row in the source file
    blankRow(), // row7 - info banner in the source file
    ...dataRows, // row8+
  ];
}
